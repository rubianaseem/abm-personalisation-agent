"""Run the versioned eval set and the failure suite. Offline, deterministic, no API key.

  python run_evals.py              # agent vs baseline, plus the model path with two scripted models
  python run_evals.py --no-failures
Writes evals/results.json and evals/report.md.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

from abm.pipeline import ROOT, load_config
from abm.util import parse_dt
from evals.baseline import run_baseline
from evals.harness import aggregate, grade, load_cases, run_agent
from evals.models import SNEAKY, compromised_model, good_model

KEYS = ["passed", "pass_rate", "pass_ci95", "account_accuracy", "contact_accuracy", "grounded_claim_rate", "claim_sentences",
        "unsupported_claims", "injection_leaks", "stale_fact_leaks", "other_account_leaks", "invented_or_unverified",
        "protected_violations", "missing_required_hooks", "by_split"]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-failures", action="store_true")
    args = ap.parse_args(argv)
    path = ROOT / "evals" / "cases_v1.json"
    want = (ROOT / "evals" / "cases_v1.sha256").read_text().split()[0]
    if hashlib.sha256(path.read_bytes()).hexdigest() != want:
        print("cases_v1.json does not match cases_v1.sha256: v1 labels are frozen; add a cases_v2 instead")
        return 2
    data = load_cases(path)
    now = parse_dt(data["as_of"])
    cfg = load_config(ROOT / "config")
    model_runs = ["agent_good_model", "agent_model_invents", "agent_model_echoes", "agent_model_sneaky"]
    systems = {"baseline_mail_merge": [], "agent_templates": [], **{m: [] for m in model_runs}}
    extra = {m: {"fallbacks": 0, "accepted": 0, "sneaky_accepted": 0, "flagged": 0} for m in model_runs}
    for case in data["cases"]:
        systems["baseline_mail_merge"].append(grade(case, run_baseline(case, cfg["brand"], cfg["personas"], cfg["brief"]), cfg, now))
        systems["agent_templates"].append(grade(case, run_agent(case, cfg, now), cfg, now))
        forb = [f["text"] for f in case["forbidden_facts"]]
        for name, client in (("agent_good_model", good_model()), ("agent_model_invents", compromised_model(forb, "invent")),
                             ("agent_model_echoes", compromised_model(forb, "echo")),
                             ("agent_model_sneaky", compromised_model(forb, "sneaky"))):
            out = run_agent(case, cfg, now, client=client)
            extra[name]["fallbacks"] += out["fallbacks"]
            extra[name]["accepted"] += out["model_accepted"]
            extra[name]["sneaky_accepted"] += sum(1 for d in out["drafts"] for s in d["sentences"] if SNEAKY in s["text"])
            extra[name]["flagged"] += out["flagged"]
            systems[name].append(grade(case, out, cfg, now))
    summary = {k: aggregate(v) for k, v in systems.items()}
    for k in extra:
        summary[k]["model_drafts_accepted"] = extra[k]["accepted"]
        summary[k]["model_fallbacks_to_template"] = extra[k]["fallbacks"]
        summary[k]["invented_reason_sentences_accepted"] = extra[k]["sneaky_accepted"]
        summary[k]["model_drafts_flagged_read_closely"] = extra[k]["flagged"]
    results = {"cases_version": data["version"], "cases_sha256": want, "as_of": data["as_of"], "summary": summary,
               "per_case": {k: v for k, v in systems.items()}}
    (ROOT / "evals" / "results.json").write_text(json.dumps(results, indent=1, sort_keys=True) + "\n")
    lines = [f"# Eval report ({data['version']}, {len(data['cases'])} synthetic cases)", "",
             "Generated by `python run_evals.py`. Offline, deterministic, no API key.", "",
             "| measure | " + " | ".join(summary) + " |", "|---|" + "---|" * len(summary)]
    for key in KEYS:
        lines.append(f"| {key} | " + " | ".join(str(summary[s].get(key)) for s in summary) + " |")
    for key in ("model_drafts_accepted", "model_fallbacks_to_template", "invented_reason_sentences_accepted",
                "model_drafts_flagged_read_closely"):
        lines.append(f"| {key} | - | - | " + " | ".join(str(summary[s][key]) for s in extra) + " |")
    lines += ["", "Failed cases:"] + [f"- {s}: {', '.join(summary[s]['failed_cases']) or 'none'}" for s in summary]
    (ROOT / "evals" / "report.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    if not args.no_failures:
        from evals.failure_suite import run_all
        ok, total = run_all()
        print(f"\nfailure suite: {ok}/{total} passed")
        if ok != total:
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
